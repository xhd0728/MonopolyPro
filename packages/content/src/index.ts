function card(
  id: string,
  name: string,
  category: CardDefinition['category'],
  effect: CardDefinition['effect'],
  amount: number,
  target: CardDefinition['target'],
  description: string,
  icon: string,
): CardDefinition {
  return {
    id,
    name,
    category,
    effect,
    amount,
    target,
    description,
    icon,
    price: 100 + Math.abs(amount > 6 ? Math.min(amount, 400) : amount * 25),
  };
}
