function makeMap(
  id: string,
  name: string,
  subtitle: string,
  description: string,
  theme: string,
  color: string,
  recommended: string,
  mechanic: MapDefinition['mechanic'],
): MapDefinition {
  let countryIndex = 0;
  const tiles: TileDefinition[] = coords.map(([x, z], index) => {
    const kind =
      index === 0
        ? 'start'
        : index === 7
          ? 'bank'
          : index === 14
            ? 'shop'
            : index === 21
              ? 'hospital'
              : [3, 10, 17, 24].includes(index)
                ? 'event'
                : [5, 19].includes(index)
                  ? 'tax'
                  : mechanic === 'ferry' && [11, 25].includes(index)
                    ? 'transit'
                    : 'property';
    const group = Math.floor(index / 7),
      price = 220 + group * 80 + (index % 3) * 35;
    const countryCode = kind === 'property' ? countryRoutes[id][countryIndex++] : undefined;
    return {
      id: `${id}-${index}`,
      index,
      name: countryCode ? COUNTRIES[countryCode] : specialNames[kind]!,
      kind,
      ...(countryCode ? { countryCode } : {}),
      x,
      z,
      group,
      price: kind === 'property' ? price : 0,
      rent: Math.round(price * 0.16),
      buildCost: Math.round(price * 0.55),
      exits: [(index + 1) % 28],
    };
  });
  if (mechanic === 'metro') {
    tiles[9].exits = [10, 18];
    tiles[23].exits = [24, 4];
  }
  if (mechanic === 'ferry') {
    tiles[11].name = '东洋港口';
    tiles[25].name = '西洋港口';
  }
  return { id, name, subtitle, description, theme, color, recommended, mechanic, tiles };
}
